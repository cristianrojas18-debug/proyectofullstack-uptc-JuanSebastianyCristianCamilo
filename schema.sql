-- Tabla: inventario_productos
-- ==============================================================================

-- 1. Crear la tabla de productos si no existe
CREATE TABLE IF NOT EXISTS public.inventario_productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(50) UNIQUE NOT NULL,
    nombre_producto VARCHAR(150) NOT NULL,
    bodega VARCHAR(100) NOT NULL,
    stock_actual INTEGER NOT NULL DEFAULT 0,
    stock_minimo INTEGER NOT NULL DEFAULT 5,
    proveedor_email VARCHAR(255) NOT NULL,
    ultima_actualizacion TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Habilitar Row Level Security (RLS)
ALTER TABLE public.inventario_productos ENABLE ROW LEVEL SECURITY;

-- 3. Crear políticas permisivas para desarrollo/demostración pública con anon key
-- Permite lectura pública
CREATE POLICY "Permitir lectura publica de inventario" 
ON public.inventario_productos 
FOR SELECT 
TO anon, authenticated 
USING (true);

-- Permite inserción pública
CREATE POLICY "Permitir insercion publica de inventario" 
ON public.inventario_productos 
FOR INSERT 
TO anon, authenticated 
WITH CHECK (true);

-- Permite actualización pública
CREATE POLICY "Permitir actualizacion publica de inventario" 
ON public.inventario_productos 
FOR UPDATE 
TO anon, authenticated 
USING (true)
WITH CHECK (true);

-- Permite eliminación pública (opcional para mantenimiento)
CREATE POLICY "Permitir eliminacion publica de inventario" 
ON public.inventario_productos 
FOR DELETE 
TO anon, authenticated 
USING (true);

-- 4. Habilitar Supabase Realtime para la tabla
ALTER PUBLICATION supabase_realtime ADD TABLE public.inventario_productos;

